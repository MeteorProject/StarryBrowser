"""Generates the Windows installer string table from starry/browser/resources/l10n.

Non-ASCII characters are emitted as universal character names so the generated
header compiles independently of source encoding.
"""

import argparse
import json
import os

# Same order as kLanguages in strings.cc.
LANGUAGES = ['zh-Hans', 'zh-Hant', 'en', 'ja', 'ko']
PREFIX = 'installer.'


def wide_literal(text):
    out = []
    for ch in text:
        code = ord(ch)
        if ch == '"' or ch == '\\':
            out.append('\\' + ch)
        elif ch == '\n':
            out.append('\\n')
        elif 0x20 <= code < 0x7f:
            out.append(ch)
        elif code <= 0xffff:
            out.append(f'\\u{code:04x}')
        else:
            out.append(f'\\U{code:08x}')
    return 'L"' + ''.join(out) + '"'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--l10n-dir', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()

    tables = {}
    for language in LANGUAGES:
        with open(os.path.join(args.l10n_dir, f'{language}.json'),
                  encoding='utf-8') as f:
            tables[language] = json.load(f)

    keys = sorted(k for k in tables['zh-Hans'] if k.startswith(PREFIX))
    lines = [
        '// Generated by starry/installer/win/generate_strings.py. Do not edit.',
        '',
        '#ifndef STARRY_INSTALLER_WIN_INSTALLER_STRINGS_H_',
        '#define STARRY_INSTALLER_WIN_INSTALLER_STRINGS_H_',
        '',
        '#include <array>',
        '#include <string_view>',
        '',
        'namespace starry::installer {',
        '',
        'struct InstallerString {',
        '  std::string_view key;',
        f'  std::array<const wchar_t*, {len(LANGUAGES)}> text;',
        '};',
        '',
        f'inline constexpr std::array<InstallerString, {len(keys)}> kInstallerStrings = {{{{',
    ]
    for key in keys:
        texts = []
        for language in LANGUAGES:
            value = tables[language].get(key, tables['en'].get(key, ''))
            if not isinstance(value, str):
                raise SystemExit(f'{key}: installer strings cannot be plurals')
            texts.append(wide_literal(value))
        lines.append(f'    {{"{key}",')
        lines.append(f'     {{{", ".join(texts)}}}}},')
    lines += [
        '}};',
        '',
        '}  // namespace starry::installer',
        '',
        '#endif  // STARRY_INSTALLER_WIN_INSTALLER_STRINGS_H_',
        '',
    ]
    with open(args.output, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))


if __name__ == '__main__':
    main()
